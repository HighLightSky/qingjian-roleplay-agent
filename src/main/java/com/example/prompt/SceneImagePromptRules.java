package com.example.prompt;

/** 整理同时生成画面草稿；绘图补充不作为领域事实。 */
public final class SceneImagePromptRules {
    private SceneImagePromptRules() {
    }

    public static void appendTo(StringBuilder prompt) {
        prompt.append("""
                \n【当前画面生图提示词】
                每轮都必须返回 sceneImage：{"prompt":"单段中文画面指令","additionalReferences":[{"assetId":"imgN","scope":"简短参考用途"}]}。
                prompt 用两三句精简单段中文，通常约80—150字；必要动作可适当增加，不凑字，不输出标题、摘要、分析或正文。
                根据 currentMessages 原文、当前剧情与持续视觉状态确定正文结束时的一个静态画面，不仅依赖 changes；同一状态多次变化时，以原文最后一次为准。
                只写最后的结果：脱下的衣物和放下的物品交代最终位置，门的开闭与灯光一致，不混入较早动作、过渡过程或尚未发生的事件。
                身份引用之后立即写最重要的1—3处变化，再写当前姿态与必要支撑，最后用短句交代环境和构图。
                第一张输入 <image1> 是程序提供的黑画布，只指定画幅，要完整绘制新画面，不继承黑色背景。
                automaticReference 存在时，程序将其作为 <image2> 优先提供人物身份；additionalReferences 不得重复选择它，额外参考从 <image3> 开始。
                automaticReference 为 null 时，额外参考从 <image2> 开始。编号严格按 additionalReferences 的数组顺序排列。
                额外参考只能选择 referenceCatalog 实际提供的资产，最多 maxAdditionalReferences 张，不选无关图片，不重复编号。
                业务 JSON 的 assetId 使用真实 imgN；prompt 中仅使用 <imageN> 引用输入图片，不写业务资产编号。
                身份已有参考时写“与<image2>相同的人物”等，不重新描述五官，不解释参考图中有什么，只讲明取用的属性。
                生图模型会实际收到所选参考图，用图片承载不变的外观；不要把材料中的服装、发型、配饰清单整段复制进 prompt，也不要照抄历史长提示词。
                变化以本次实际采用的参考图为比较对象，优先突出穿脱、姿态、持物和地点的差异；即使本轮没有新变化，持续状态与参考不同时仍须明确写出。
                差异只依据实际原图、已有观察和对话事实判断；参考细节未知时直接写必要的当前状态，不猜测参考图的外观。
                默认省略未变化的发型、配饰、内搭和逐件服装清单；只保留与当前变化直接相关或用户特别强调的属性。没有身份参考时只补充辨认人物必需且有依据的外观。
                穿外套时必须交代层叠与穿着关系：“在参考图原有上衣外加穿外套，外套覆盖肩部和双臂，双臂穿入袖管，前襟扣合”；不再逐件列出被覆盖的内搭。脱外套时写清露出的衣物及外套最终位置。
                明确主要姿态、朝向和视线；只补齐与动作有关的手脚、持物和支撑关系，例如“坐在书桌旁的椅子上，双脚落地”。同一只手只承担一个当前动作，视线与目标位置一致。
                环境只留当前地点、必要光线及影响动作的物体，不展开与主体动作无关的远景、天气细节或氛围词；构图简述即可。
                可补齐成画必需细节，但不得改变用户明确要求、已确定服装、人物关系或剧情结果，不为突出变化编造服装颜色、款式或新道具。
                穿衣写法示例：与<image2>相同的人物，在原有上衣外加穿外套，肩部和双臂被外套覆盖，双臂穿入袖管，前襟扣合。站在窗边，右手扶窗台，侧头看向窗外。日光，中景。
                脱衣写法示例：与<image2>相同的人物，外套已脱下搭在椅背，身上穿白衬衫。坐在书桌旁的椅子上，左手扶书，右手搭书页，低头阅读。窗边日光，侧面中景。
                示例只示范写法，细节以本轮依据为准。返回前删去关键变化以外的服装清单、发型配饰和背景铺陈，保留关键变化的可见结果。
                参考目录的已有观察是有损记录，生成要求未经图像核实；不能声称本轮看过未实际提供的原图。
                绘图补充只写入 sceneImage.prompt，不得作为 storyChanges、visualChanges、memoryChanges、goalChanges 或原图观察的证据。
                """);
    }
}
