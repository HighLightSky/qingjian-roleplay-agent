package com.example.prompt;

import com.example.web.dto.ChatApiRequest;

public final class SceneImagePromptRules {
    private SceneImagePromptRules() {
    }

    public static void appendTo(StringBuilder prompt, ChatApiRequest request) {
        prompt.append("""
        \n【生图提示词生成规则：必须遵守】

        一、输出协议

        每次回复必须依次包含角色正文、可选的画面计划，以及最终的生图提示词。
        无论用户是否明确要求生图、剧情变化是否明显、是否存在额外参考图，
        都必须在本轮输出中生成完整的生图提示词，不得省略。

        角色正文的篇幅要求不约束生图提示词。
        生图提示词必须位于整个回复的末尾，不得在其后继续输出角色正文、解释或闲聊。

        需要额外参考图片时，在 [生图提示词] 之前输出 [画面计划]，
        下一行输出一个合法的 JSON 对象；不需要额外参考图片时，
        省略 [画面计划] 和对应 JSON。

        [画面计划] 仅用于程序选择参考图片，不是绘图描述。
        JSON 结构固定为：
        {"referenceImages":[{"assetId":"imgN","roles":["identity"],"scope":"具体参考哪些属性"}]}

        referenceImages 可以包含零张或多张图片。
        assetId 必须来自当前实际提供的资产清单，不得编造、猜测或改写编号。
        roles 只能使用 identity、continuity、outfit、environment、pose、prop。
        scope 必须明确指出这张图片具体提供哪些视觉信息，不得只写笼统的用途。
        JSON 必须符合标准语法，不添加注释、Markdown 代码块或额外字段。
        不得为了填满列表而选择无关图片；只选择对当前画面确有帮助的参考图。

        二、画面状态与事实约束

        生图提示词描绘的是角色正文结束时已经成立的一个静态画面，
        而不是整段剧情、动作过程、未来事件或不可见的心理活动。

        生成前，先在内部确定以下信息：
        1. 当前画面中有哪些实际可见的人物，以及各自的身份。
        2. 每个人物当前已经确定的服装、发型和外观。
        3. 人物正在呈现的最终姿势、肢体位置、朝向、视线和表情。
        4. 当前地点、空间布局、道具位置及人物与物体的关系。
        5. 当前画面中哪些信息来自明确剧情，哪些需要沿用历史视觉状态。

        这些判断只用于组织最终提示词，不额外输出分析过程。

        必须区分已确定事实与模型补充的视觉细节。
        用户明确指定的内容优先；当前剧情已经确立的事实不得擅自改变；
        尚未确定的细节可以合理补充，但不能与已有事实冲突。

        不得把未发生的动作写成已完成的状态，也不得把连续动作同时塞入一张静态画面。
        剧情变化较小时，允许沿用当前有效的视觉状态，不必为了制造变化而更换姿势、
        服装、地点或镜头。需要合理补充时，只补充有助于画面成立的必要细节。

        三、视觉连续性与场景更新

        视觉连续性是对当前有效状态的延续，而不是对上一张图的机械复制。

        角色的身份、发型、服装、道具和场景分别判断是否需要延续，
        不得默认一张历史图片中的所有视觉属性都必须保留。

        明确要求与当前剧情状态优先于历史图片。
        角色换装后，使用新服装；角色移动后，更新人物位置；
        场景切换后，使用新场景，不继承旧背景；
        道具被拿起、放下、移动或移交后，更新其位置和持有者。

        没有明确依据时，不得擅自认定服装已经更换、道具已经出现或消失，
        也不得把历史图片中的偶然细节升级为当前剧情事实。

        四、参考图片选择与用途隔离

        第一张纯黑画布由程序提供，仅用于指定画幅与底图。
        它不是人物或场景参考，不得将其加入 referenceImages，
        不得从中推断人物身份、服装、姿势、环境或画面风格。

        角色照片由程序优先提供。当当前画面包含该角色且角色照片可用时，
        优先使用其作为 identity 参考；没有角色照片时，
        可以考虑使用仍然有效且适合识别该角色的历史生成图。
        角色照片与历史生成图均不是无条件必选项。

        各种 roles 的使用规则如下：

        - identity：只参考人物身份与可识别的外观特征，
          例如脸型、五官、肤色及需要保持的发型特征。
          不得因此自动继承该图片中的服装、动作或背景。

        - continuity：参考仍然有效的历史视觉状态，
          例如发型、妆容、人物间相对位置或持续存在的视觉细节。
          不得继承已经被剧情改变的状态。

        - outfit：参考当前仍然有效的服装款式、颜色、材质和穿着方式。
          如果剧情已明确换装，必须服从新服装状态。

        - environment：参考当前场景的空间布局、背景、家具和环境特征。
          场景已改变时，不得继续沿用旧场景。

        - pose：参考与当前动作要求相关的身体姿态、肢体位置、
          身体朝向及人物与物体的接触关系。
          严格要求不得机械复制参考图中的旧姿势。

        - prop：参考指定道具的外观、结构、颜色及细节。
          道具的当前位置和持有者以剧情状态为准。

        只有在相应属性需要参考时，才选择对应图片。
        同一图片可以承担多个用途，但每个用途都必须合理且明确。
        优先选择最少且足够的参考图片，避免无关参考造成视觉冲突。

        历史图片是可选的视觉参考，不是必须编辑的前幕。
        可以从程序提供且本轮尚未重读的历史图片中选择参考，
        但不能仅凭资产编号声称知道图片的具体内容。
        如果图片内容不可见且没有可信描述，只能依据已知元数据选择用途，
        不得虚构其中的细节。无法确认某项视觉信息时，应使用当前已知状态，
        不得把未经核实的猜测写成确定事实。

        五、提示词组织原则

        [生图提示词] 标识之后，说明“不使用参考图中角色的动作，角色动作以下文为准：”
        用最直白的语言描述角色的动作（手放在哪里、脚放在哪里、侧身、抬头低头、身体部位的动作、站立、坐、蹲、躺卧、俯下身、撅屁股等），
        表情（睁眼闭眼、笑、哭、平静等）
        与摄像机的状态（目视摄像机、目视图像左侧/右侧、背对摄像机），
        人物在图中的占比（全身，可以看到头和脚；半身，只能看到膝盖以上，等等，需要明确图中人物占比）

        如果环境场景和图片氛围与参考图中场景一致，不必写。如果不一致，用简短的语言描述。

        六、描述质量与生成约束

        提示词优先描述能够直接影响生成结果的内容，尽量用可以看见的描述性语言

        动作应具有明确的身体姿态和空间关系。
        涉及人物扶桌、坐椅、持物、拥抱或接触其他物体时，
        应描述接触部位、相对位置、支撑关系和必要的遮挡关系，
        避免人物悬浮、物体穿模或肢体关系不合理。

        人物的脸部、服装、肢体与场景应在光照、透视、比例和色调上协调。
        不得为了追求画面效果而改变用户指定的人物身份、动作、服装或场景。

        不额外输出独立的负面提示词段落。
        将必要的禁止事项整合进对应的六段描述中；
        不添加与当前画面无关的通用限制，也不重复堆砌同义约束。

        生图提示词是提交给图像生成模型的视觉指令，
        不是对实际生成结果的描述，也不能据此认定图片已经生成或核实。

        七、最终输出检查

        输出前在内部检查以下事项：
        1. 本轮角色正文是否完整，生图提示词是否必定存在。
        2. 是否准确反映正文结束时的当前画面。
        3. 是否遵守本轮明确要求以及已确定的视觉状态。
        4. 参考图片是否真实存在，选择用途是否正确。
        5. 是否将已经变化的服装、动作、道具或背景错误地继承下来。
        6. 是否存在互相矛盾、无法同时成立或缺乏依据的描述。
        7. 是否在生图提示词后输出了任何额外内容。

        只输出最终角色正文、必要的 [画面计划] JSON 和 [生图提示词]。
        不输出检查过程、规则复述或额外说明。
        """);
        prompt.append("绑定角色照片：").append(request.character().appearancePhotoAssetId()).append('\n');
        prompt.append("当前视觉状态：").append(request.state().visualState()).append('\n');
    }
}
